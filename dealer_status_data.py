def normalize_hr_data(df: pd.DataFrame) -> pd.DataFrame:
    """Chuẩn hóa bảng dữ liệu nhân sự, đảm bảo đầy đủ cột và không lỗi NaN."""
    if df is None or df.empty:
        return get_initial_hr_data()
    result = df.copy()
    for col in HR_COLUMNS:
        if col not in result.columns:
            result[col] = ""
        result[col] = result[col].fillna("").astype(str).str.strip()

    # Tự sinh Mã NS nếu người dùng thêm dòng mới
    existing_codes = set(result["Mã NS"])
    next_idx = len(result) + 1
    for idx in result.index:
        code = result.at[idx, "Mã NS"]
        if not code:
            while f"NS-{next_idx:02d}" in existing_codes:
                next_idx += 1
            new_code = f"NS-{next_idx:02d}"
            result.at[idx, "Mã NS"] = new_code
            existing_codes.add(new_code)
            next_idx += 1
        status = result.at[idx, "Trạng thái"]
        if status not in HR_STATUSES:
            result.at[idx, "Trạng thái"] = (
                "Đã nhận việc" if result.at[idx, "Họ tên"] else "Đang tuyển dụng"
            )
    return result[HR_COLUMNS].reset_index(drop=True)


def apply_hr_updates(target_df: pd.DataFrame, edited_df: pd.DataFrame, is_filtered: bool | None = None) -> pd.DataFrame:
    """Áp dụng các thay đổi từ st.data_editor vào bảng nhân sự tổng."""
    target = normalize_hr_data(target_df)
    edited = normalize_hr_data(edited_df)
    if is_filtered is False and len(edited) == len(target):
        return edited

    updated = target.copy()
    existing_map = {row["Mã NS"]: idx for idx, row in updated.iterrows()}
    new_rows = []
    for _, row in edited.iterrows():
        code = row["Mã NS"]
        if code in existing_map:
            t_idx = existing_map[code]
            for col in HR_COLUMNS:
                updated.at[t_idx, col] = row[col]
        else:
            new_rows.append(row.to_dict())
    if new_rows:
        updated = pd.concat([updated, pd.DataFrame(new_rows)], ignore_index=True)
    return normalize_hr_data(updated)


